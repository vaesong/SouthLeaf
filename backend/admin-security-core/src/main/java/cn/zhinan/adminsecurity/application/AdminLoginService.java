package cn.zhinan.adminsecurity.application;

import cn.zhinan.adminsecurity.domain.AdminAccount;
import cn.zhinan.adminsecurity.domain.AdminAuthenticationException;
import cn.zhinan.adminsecurity.domain.AuthenticationEvent;
import cn.zhinan.adminsecurity.domain.CredentialDependencyException;
import cn.zhinan.adminsecurity.domain.PasswordInput;
import cn.zhinan.adminsecurity.port.AuthenticationEventSink;
import cn.zhinan.adminsecurity.port.CredentialLookup;
import cn.zhinan.adminsecurity.port.PasswordVerifier;
import java.time.Clock;
import java.time.temporal.ChronoUnit;
import java.util.Arrays;
import java.util.Objects;
import java.util.UUID;

/** Unwired pure use case. KDF is outside transactions; issuance rechecks the captured version. */
public final class AdminLoginService {
  private final CredentialLookup lookup;
  private final PasswordVerifier verifier;
  private final AdminSessionService sessions;
  private final AuthenticationEventSink events;
  private final Clock clock;

  public AdminLoginService(
      CredentialLookup lookup,
      PasswordVerifier verifier,
      AdminSessionService sessions,
      AuthenticationEventSink events,
      Clock clock) {
    this.lookup = Objects.requireNonNull(lookup);
    this.verifier = Objects.requireNonNull(verifier);
    this.sessions = Objects.requireNonNull(sessions);
    this.events = Objects.requireNonNull(events);
    this.clock = Objects.requireNonNull(clock);
  }

  /** requestId is generated by a trusted caller. Caller owns and must clear its original array. */
  public AdminSessionService.IssuedSession login(
      String accountId, char[] password, UUID requestId) {
    Objects.requireNonNull(requestId);
    // Reject oversized/malformed input before allocating a copy or invoking any KDF/store.
    if (!PasswordInput.isBounded(password)) throw denied(null, requestId);
    char[] owned = password.clone();
    try {
      if (!AdminAccount.isValidAccountId(accountId)) {
        verifier.consumeDummyCost(owned);
        throw denied(null, requestId);
      }
      var candidate = lookup.find(accountId);
      if (candidate.isEmpty()) {
        verifier.consumeDummyCost(owned);
        throw denied(null, requestId);
      }
      var fact = candidate.get();
      if (!accountId.equals(fact.accountId()))
        throw new CredentialDependencyException(
            CredentialDependencyException.Reason.INCONSISTENT_LOOKUP);
      if (!fact.enabled()) {
        verifier.consumeDummyCost(owned);
        throw denied(fact.accountId(), requestId);
      }
      var match = verifier.verify(owned, fact.credentialHash());
      if (!match.matches()) throw denied(fact.accountId(), requestId);
      if (match.upgradeRequired())
        record(AuthenticationEvent.Kind.CREDENTIAL_UPGRADE_REQUIRED, fact.accountId(), requestId);
      try {
        // No caller-supplied version. A reset/disable/access change during KDF denies issuance.
        return sessions.openForVerifiedCredentials(fact.accountId(), fact.securityVersion());
      } catch (AdminAuthenticationException changed) {
        throw denied(fact.accountId(), requestId);
      }
    } finally {
      Arrays.fill(owned, '\0');
    }
  }

  private AdminAuthenticationException denied(String knownId, UUID requestId) {
    record(AuthenticationEvent.Kind.LOGIN_DENIED, knownId, requestId);
    return new AdminAuthenticationException();
  }

  private void record(AuthenticationEvent.Kind kind, String knownId, UUID requestId) {
    events.append(
        new AuthenticationEvent(
            kind, knownId, requestId, clock.instant().truncatedTo(ChronoUnit.MICROS)));
  }
}
